CREATE TABLE calculation_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wind_speed NUMERIC(12, 4) NOT NULL,
    height NUMERIC(12, 4) NOT NULL,
    diameter NUMERIC(12, 4) NOT NULL,
    air_density NUMERIC(12, 4) NOT NULL,
    power_coefficient NUMERIC(12, 4) NOT NULL,
    swept_area NUMERIC(16, 4) NOT NULL,
    raw_power_kw NUMERIC(16, 4) NOT NULL,
    net_power_kw NUMERIC(16, 4) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX calculation_results_created_at_idx
    ON calculation_results (created_at DESC);
